"""World land mask for the city map (web/src/worldmask.ts): equirectangular grid, one bit per cell.

    python3 scripts/world_mask.py ne_110m_land.geojson

Input: Natural Earth 110m land polygons (public domain, naturalearthdata.com). Pillow draws them at 4x and a cell is land
when at least half of it is covered. The grid spans lon -180..180 and lat LAT_N..LAT_S (no poles).
"""
import base64, json, os, sys
from PIL import Image, ImageDraw

W, H, LAT_N, LAT_S = 240, 92, 80.0, -58.0
S = 4
img = Image.new('L', (W * S, H * S), 0)
dr = ImageDraw.Draw(img)
px = lambda lon, lat: ((lon + 180) / 360 * W * S, (LAT_N - lat) / (LAT_N - LAT_S) * H * S)
for f in json.load(open(sys.argv[1], encoding='utf-8'))['features']:
    g = f['geometry']
    for poly in (g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]):
        dr.polygon([px(*p[:2]) for p in poly[0]], fill=255)
        for hole in poly[1:]:
            dr.polygon([px(*p[:2]) for p in hole], fill=0)
small = img.resize((W, H), Image.BOX)
bits = bytearray((W * H + 7) // 8)
for n, v in enumerate(small.tobytes()):
    if v >= 128:
        bits[n >> 3] |= 128 >> (n & 7)
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'web', 'src', 'worldmask.ts')
open(out, 'w').write("// generated by scripts/world_mask.py (Natural Earth 110m land)\nexport const WORLD: {w: number; h: number; latN: number; latS: number; bits: string} = {w: %d, h: %d, latN: %s, latS: %s, bits: '%s'};\n" % (W, H, LAT_N, LAT_S, base64.b64encode(bytes(bits)).decode()))
rows = [''.join('#' if (bits[(y * W + x) >> 3] >> (7 - ((y * W + x) & 7))) & 1 else '.' for x in range(0, W, 2)) for y in range(0, H, 3)]
print('\n'.join(rows))
